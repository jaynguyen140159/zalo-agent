    "  var STORE_KEY = 'km_portal_static_store_v1';",
    "  function ensureCustomerSchema(st) {",
    "    if (!st.nextIds) st.nextIds = { customer: 1, project: 10, stage: 100, task: 100, cost: 100, wt: 10 };",
    "    if (!st.nextIds.customer) st.nextIds.customer = 1;",
    "    if (!Array.isArray(st.customers)) st.customers = [];",
    "    (st.projects || []).forEach(function(p) {",
    "      if (!p.business_unit) p.business_unit = 'KM Gift';",
    "      if (!p.customer_id) {",
    "        var q = (st.quotations && st.quotations[p.id]) || {};",
    "        var cname = (q.customer_name || p.name.split(' - ')[0] || p.name || 'Khách hàng').trim();",
    "        var found = st.customers.find(function(c) { return (c.name || '').trim().toLowerCase() === cname.toLowerCase(); });",
    "        if (!found) {",
    "          found = { id: st.nextIds.customer++, name: cname, tax_code: q.customer_tax_code || '', contact_name: q.contact_name || q.customer_rep || '', contact_phone: q.contact_phone || '', notes: '' };",
    "          st.customers.push(found);",
    "        }",
    "        p.customer_id = found.id;",
    "      }",
    "    });",
    "  }",
    "  function buildProjectsAndCustomers(st) {",
    "    ensureCustomerSchema(st);",
    "    var custById = {};",
    "    st.customers.forEach(function(c) { custById[c.id] = c; });",
    "    var enrichedProjects = st.projects.map(function(p) {",
    "      var pt = st.tasks.filter(function(t) { return t.project_id === p.id; });",
    "      var ps = st.stages.filter(function(s) { return s.project_id === p.id; });",
    "      var pc = st.costs.filter(function(c) { return c.project_id === p.id; });",
    "      var doneCnt = pt.filter(function(t) { return t.progress >= 100 || t.status === 'completed'; }).length;",
    "      var overall = pt.length ? Math.round(pt.reduce(function(s, t) { return s + (t.progress || 0); }, 0) / pt.length) : 0;",
    "      var tc = 0, tq = 0;",
    "      pc.forEach(function(c) { var q = Math.max(1, Number(c.quantity) || 1); tc += (Number(c.cost_amount) || 0) * q; tq += Math.round((Number(c.cost_amount) || 0) * (Number(c.markup_factor) || 1.5)) * q; });",
    "      var qMeta = (st.quotations && st.quotations[p.id]) || {};",
    "      var vatPctP = qMeta.vat_percent !== undefined && qMeta.vat_percent !== null ? Number(qMeta.vat_percent) : 8;",
    "      var vatAmtP = Math.round(tq * vatPctP / 100);",
    "      var estProfit = tq - vatAmtP - tc;",
    "      var marginPct = tq > 0 ? Math.round(estProfit * 100 / tq) : 0;",
    "      var paidCnt = pc.filter(function(c) { return String(c.payment_status || '').indexOf('100%') !== -1; }).length;",
    "      var linkedC = p.customer_id ? custById[p.customer_id] : null;",
    "      return Object.assign({}, p, {",
    "        contract_code: p.contract_code || '',",
    "        customer_id: p.customer_id || null,",
    "        customer_name: (linkedC && linkedC.name) || qMeta.customer_name || '',",
    "        customer_tax_code: (linkedC && linkedC.tax_code) || qMeta.customer_tax_code || '',",
    "        contact_name: (linkedC && linkedC.contact_name) || qMeta.contact_name || '',",
    "        contact_phone: (linkedC && linkedC.contact_phone) || qMeta.contact_phone || '',",
    "        tasks_count: pt.length, completed_tasks: doneCnt, overall_progress: overall, stages_count: ps.length,",
    "        total_cost: tc, total_quote: tq, total_revenue: tq, vat_percent: vatPctP, vat_amount: vatAmtP, estimated_profit: estProfit, profit_margin_pct: marginPct,",
    "        items_preview: pc.slice(0, 2).map(function(c) { return c.item_name; }).join(', ') + (pc.length > 2 ? ' (+' + (pc.length - 2) + ')' : ''),",
    "        vendors_preview: pc.slice(0, 2).map(function(c) { return c.vendor_name; }).filter(Boolean).join(', '),",
    "        payment_summary: pc.length ? paidCnt + '/' + pc.length + ' Đã TT' : 'Chưa có khoản chi'",
    "      });",
    "    });",
    "    var customers = st.customers.map(function(cust) {",
    "      var projs = enrichedProjects.filter(function(p) { return Number(p.customer_id) === Number(cust.id); });",
    "      var rev = projs.reduce(function(s, p) { return s + (Number(p.total_revenue) || 0); }, 0);",
    "      var cost = projs.reduce(function(s, p) { return s + (Number(p.total_cost) || 0); }, 0);",
    "      var vat = projs.reduce(function(s, p) { return s + (Number(p.vat_amount) || 0); }, 0);",
    "      var prof = projs.reduce(function(s, p) { return s + (Number(p.estimated_profit) || 0); }, 0);",
    "      return Object.assign({}, cust, {",
    "        projects_count: projs.length,",
    "        unit_counts: {",
    "          km_gift: projs.filter(function(p) { return p.business_unit === 'KM Gift'; }).length,",
    "          km_brand: projs.filter(function(p) { return p.business_unit === 'KM Brand'; }).length,",
    "          homeplanner: projs.filter(function(p) { return p.business_unit === 'Homeplanner'; }).length",
    "        },",
    "        total_revenue: rev, total_cost: cost, total_vat: vat, total_profit: prof,",
    "        profit_margin_pct: rev > 0 ? Math.round(prof * 100 / rev) : 0",
    "      });",
    "    });",
    "    return { enrichedProjects: enrichedProjects, customers: customers };",
    "  }",
    "  function loadStore() {",
    "    try {",
    "      var raw = localStorage.getItem(STORE_KEY);",
